# ── --repo ───────────────────────────────────────────────────────────────────
class RepoBindingTests(unittest.TestCase):
    FOUR = ("REPO", "MANIFEST", "WEB", "DB")

    def test_repo_is_a_top_level_option_not_a_subparser(self):
        src = inspect.getsource(ctx.main)
        self.assertIn('add_argument("--repo"', src)
        self.assertLess(src.index('add_argument("--repo"'), src.index("add_subparsers"))
        self.assertNotIn('add_parser("repo")', src)
        self.assertIn("_bind_repo(args.repo)", src)
        # the two guards that scrape subcommands must not see it
        self.assertEqual(re.findall(r'add_parser\("repo"\)', open(CTX_PATH).read()), [])

    def test_bind_repo_rebinds_exactly_the_four_path_globals(self):
        saved = {k: getattr(ctx, k) for k in self.FOUR} | {"_MANIFEST_WARNED": ctx._MANIFEST_WARNED}
        try:
            with tempfile.TemporaryDirectory() as tmp:
                ctx._MANIFEST_WARNED = True
                before = dict(vars(ctx))
                ctx._bind_repo(os.path.join(tmp, "."))         # relative-ish: abspath'd
                self.assertEqual(ctx.REPO, os.path.abspath(tmp))
                self.assertEqual(ctx.MANIFEST, os.path.join(ctx.REPO, "context_map.json"))
                self.assertEqual(ctx.WEB, os.path.join(ctx.REPO, "RESEARCH_WEB.md"))
                self.assertEqual(ctx.DB, os.path.join(ctx.REPO, "live", "state.db"))
                self.assertFalse(ctx._MANIFEST_WARNED, "the spoken-absence line is per binding")
                after = dict(vars(ctx))
                changed = {k for k in before if k in after and before[k] is not after[k]}
                self.assertEqual(changed, set(self.FOUR) | {"_MANIFEST_WARNED"})
                self.assertEqual(set(after) - set(before), set(), "bind_repo added a global")
        finally:
            for k, v in saved.items():
                setattr(ctx, k, v)
        self.assertEqual(ctx.REPO, REPO)

    def test_bind_repo_refuses_a_non_directory(self):
        saved = {k: getattr(ctx, k) for k in self.FOUR}
        try:
            with self.assertRaises(SystemExit):
                ctx._bind_repo(os.path.join(REPO, "no-such-dir-xyz"))
        finally:
            for k, v in saved.items():
                setattr(ctx, k, v)
        self.assertEqual(ctx.REPO, REPO)


