# ── SCHEMA dict ──────────────────────────────────────────────────────────────
class SchemaDictTests(unittest.TestCase):
    def test_the_historical_names_are_aliases_by_identity(self):
        self.assertIs(ctx.EDGE_TYPES, ctx.SCHEMA["edge_types"])
        self.assertIs(ctx.RELIANCE_EDGES, ctx.SCHEMA["reliance"])
        self.assertIs(ctx._PROPAGATION_EXEMPT, ctx.SCHEMA["propagation_exempt"])
        self.assertIs(ctx.STATUS_VALUES, ctx.SCHEMA["status"])
        self.assertIs(ctx.REASON_CODES, ctx.SCHEMA["reasons"])
        self.assertEqual(ctx.SCHEMA_VERSION, ctx.SCHEMA["schema_version"])
        self.assertEqual(ctx.SCHEMA["kinds"], {"F", "H", "E", "D"})
        self.assertEqual(len(ctx.SCHEMA["edge_types"]), 12)
        self.assertEqual(len(ctx.SCHEMA["reasons"]), 8)

    def test_the_id_regexes_derive_from_the_kinds(self):
        self.assertEqual(ctx._KIND_CLASS, "[" + "".join(sorted(ctx.SCHEMA["kinds"])) + "]")
        for ok in ("F1", "H22", "E3", "D297800"):
            self.assertTrue(ctx.ID_RX.match(ok), ok)
            self.assertEqual(ctx._NODE_REF_RX.findall(f"see {ok} and"), [ok])
        for bad in ("X1", "F", "1F", "f1", "AP12", "F1a", "code:x"):
            self.assertIsNone(ctx.ID_RX.match(bad), bad)
        m = ctx.SUPERSEDED_TAG_RX.search("[SUPERSEDED by F13] old title")
        self.assertEqual((m.group(1), m.group(2)), ("SUPERSEDED", "F13"))
        m = ctx.SUPERSEDED_TAG_RX.search("[retracted by D4] old title")
        self.assertEqual((m.group(1).lower(), m.group(2)), ("retracted", "D4"))
        self.assertIsNone(ctx.SUPERSEDED_TAG_RX.search("[SUPERSEDED by X9]"))
        # the unified graph's wider grammar is a separate, documented namespace
        self.assertTrue(ctx._is_idea_id("AP12"))
        self.assertFalse(ctx._is_idea_id("mod:x.py"))

    def test_no_kind_literal_survives_in_ctx_or_note(self):
        for path in (CTX_PATH, NOTE_PATH):
            src = open(path, encoding="utf-8").read()
            self.assertEqual(KIND_LITERAL_RX.findall(src), [], f"{path} re-spells the kinds")

    def test_note_reads_the_same_vocabulary_objects(self):
        self.assertIs(note.KINDS, ctx.SCHEMA["kinds"])
        src = inspect.getsource(note.lint_nodes)
        self.assertIn("ctx.ID_RX", src)
        self.assertIn("ctx.SUPERSEDED_TAG_RX", src)
        self.assertIn("m.group(2)", src)
        # the literal name tests/test_note_link.py pins must still be spelled in note's writers
        self.assertIn("RELIANCE_EDGES", inspect.getsource(note.cmd_link))

    def test_graph_compact_idea_set_derives_from_the_kinds(self):
        src = inspect.getsource(ctx._graph_compact)
        self.assertIn('SCHEMA["kinds"] | {"area"}', src)


