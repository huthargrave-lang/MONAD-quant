"""The engine seam inside tools/ctx.py is measured, not drafted (seam slice 1b).

tools/ctx.py is one file with three layers marked by banners — CORE (repo / git /
manifest / edit policy / query-navigate), ENGINE (the repo-agnostic web / graph / render /
health / search engine) and RIM (MONAD adapters: state.db, config.py, ops/, the SEC-lab
projections, perf prose) — and a bottom-of-file surface declaration: CORE_API / ENGINE_API /
RIM_API. Those tuples were GENERATED by the AST scan in this file (every `ctx.<name>` the
seven in-repo consumers reach, bucketed by the banner region that defines the name), and
this file re-runs the scan so they cannot drift from the truth:

  * scan == CORE_API ∪ ENGINE_API ∪ RIM_API, exactly — nothing unlisted, nothing stale;
  * the tuples are disjoint and every name exists on the module;
  * each name's DEFINING region is the layer its tuple claims;
  * RIM names are reached only by tools/research_ui.py (the SEC lab's host page);
  * the consumer list is complete: every non-test .py under tools/ or src/ that imports
    ctx is in CONSUMERS, so a new consumer cannot slip in unscanned;
  * eight layer banners in the ratified order CORE, RIM, ENGINE, RIM, ENGINE, RIM, ENGINE,
    RIM — ENGINE re-opened after every RIM block (skeptic r2, fix 4);
  * no ENGINE-region function or constant references a RIM-region name except through
    the declared SEAMS: the REDACT and BANNER hooks (defaults = this repo's `_redact` /
    `_web_banner`, by identity, so MONAD's output is byte-identical) and _RUNTIME_ARTIFACTS
    (rim data `doc_topology` reads — a Stage-2 manifest `integrations` item, named here
    so the debt is documented rather than hidden);
  * `_ui_tokens` resolves from __file__, not REPO — under `--repo` a foreign tools/ must
    not shadow the kit's palette;
  * `--repo PATH` is a TOP-LEVEL option (invisible to the `add_parser("…")` guards in
    tests/test_context_map.py and tests/test_cli_smoke.py) and `_bind_repo` rebinds exactly
    the four path globals the tests and note.py already reassign, restored in `finally`;
  * the single in-code SCHEMA dict IS the vocabulary: the historical names are aliases of
    its entries by identity, the id regexes derive from its kinds, tools/note.py reads the
    same objects, and no `[FHED]`-style literal survives in either file.

Direction is asymmetric on purpose: CORE → ENGINE references (cmd_find / cmd_impact reach
into the bridge helpers) are allowed and not guarded; ENGINE → RIM is the layering that the
seam exists to prevent.
"""
import ast
import inspect
import os
import re
import sys
import tempfile
import unittest

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TOOLS = os.path.join(REPO, "tools")
sys.path.insert(0, TOOLS)
import ctx  # noqa: E402
import note  # noqa: E402

CTX_PATH = os.path.join(TOOLS, "ctx.py")
NOTE_PATH = os.path.join(TOOLS, "note.py")
# The in-repo consumers (every non-test module that imports ctx; asserted complete below).
CONSUMERS = (
    "tools/note.py", "tools/research_ui.py", "tools/export_pages.py",
    "tools/epistemic_audit_lab.py", "tools/graphify_bridge.py", "tools/admit.py",
    "src/research/prereg.py",
)
LAYERS = ("CORE", "ENGINE", "RIM")
BANNER_RX = re.compile(r"^# ═══ (CORE|ENGINE|RIM|CLI)\b")
EXPECTED_ORDER = ["CORE", "RIM", "ENGINE", "RIM", "ENGINE", "RIM", "ENGINE", "RIM"]
HOOKS = {"REDACT": "_redact", "BANNER": "_web_banner"}
# Literal spellings of the kind vocabulary that must not exist outside SCHEMA["kinds"].
KIND_LITERAL_RX = re.compile(r"\[(?:[FHED]){4}\]")


# ── scanner (the generator of the tuples) ─────────────────────────────────────
def _ctx_aliases(tree):
    """Names the module is bound to in this file: `import ctx`, `import ctx as _ctx`."""
    out = set()
    for n in ast.walk(tree):
        if isinstance(n, ast.Import):
            out |= {a.asname or a.name for a in n.names if a.name == "ctx"}
    return out


def _imports_ctx(tree):
    for n in ast.walk(tree):
        if isinstance(n, ast.Import) and any(a.name == "ctx" for a in n.names):
            return True
        if isinstance(n, ast.ImportFrom) and n.module == "ctx":
            return True
    return False


def consumer_uses(rel):
    """Every attribute reached through the ctx alias(es) in one consumer: `ctx.<attr>`."""
    tree = ast.parse(open(os.path.join(REPO, rel), encoding="utf-8").read())
    aliases = _ctx_aliases(tree)
    return {n.attr for n in ast.walk(tree)
            if isinstance(n, ast.Attribute) and isinstance(n.value, ast.Name)
            and n.value.id in aliases}


def scan():
    return {rel: consumer_uses(rel) for rel in CONSUMERS}


def banner_regions(src):
    """[(lineno, layer)] in file order, from the `# ═══ LAYER` banners."""
    out = []
    for i, line in enumerate(src.splitlines(), 1):
        m = BANNER_RX.match(line)
        if m:
            out.append((i, m.group(1)))
    return out


def layer_of(regions, lineno):
    lay = None
    for start, layer in regions:
        if lineno >= start:
            lay = layer
    return lay


def top_level(src):
    """{name: (lineno, node)} for every top-level def / class / simple assignment."""
    out = {}
    for node in ast.parse(src).body:
        if isinstance(node, (ast.FunctionDef, ast.ClassDef)):
            out[node.name] = (node.lineno, node)
        elif isinstance(node, ast.Assign):
            for t in node.targets:
                if isinstance(t, ast.Name):
                    out[t.id] = (node.lineno, node)
    return out


def _loads(node):
    return {n.id for n in ast.walk(node) if isinstance(n, ast.Name) and isinstance(n.ctx, ast.Load)}


class _Source:
    @classmethod
    def setUpClass(cls):
        cls.src = open(CTX_PATH, encoding="utf-8").read()
        cls.regions = banner_regions(cls.src)
        cls.top = top_level(cls.src)
        cls.by_layer = {}
        for name, (lineno, _) in cls.top.items():
            cls.by_layer.setdefault(layer_of(cls.regions, lineno), set()).add(name)
        cls.scanned = scan()
        cls.union = set().union(*cls.scanned.values())
        cls.declared = {"CORE": set(ctx.CORE_API), "ENGINE": set(ctx.ENGINE_API),
                        "RIM": set(ctx.RIM_API)}


# ── the API tuples equal the scan ────────────────────────────────────────────
class ApiTuplesEqualTheScanTests(_Source, unittest.TestCase):
    def test_the_consumer_list_is_complete(self):
        found = set()
        for top_dir in ("tools", "src"):
            for dirpath, dirnames, filenames in os.walk(os.path.join(REPO, top_dir)):
                dirnames[:] = [d for d in dirnames if d not in ("__pycache__", "vendor")]
                for fn in filenames:
                    if not fn.endswith(".py") or fn.startswith("test_"):
                        continue
                    path = os.path.join(dirpath, fn)
                    rel = os.path.relpath(path, REPO)
                    if rel == "tools/ctx.py":
                        continue
                    try:
                        tree = ast.parse(open(path, encoding="utf-8").read())
                    except SyntaxError:
                        continue
                    if _imports_ctx(tree):
                        found.add(rel)
        self.assertEqual(found, set(CONSUMERS),
                         "a module that imports ctx is missing from CONSUMERS (or one listed "
                         "no longer imports it) — the scan must see every consumer")

    def test_scan_equals_the_union_of_the_three_tuples(self):
        declared = set().union(*self.declared.values())
        self.assertEqual(self.union - declared, set(), "consumer reaches an UNLISTED ctx name")
        self.assertEqual(declared - self.union, set(), "tuple lists a name no consumer reaches")

    def test_tuples_are_disjoint_and_every_name_exists(self):
        self.assertFalse(self.declared["CORE"] & self.declared["ENGINE"])
        self.assertFalse(self.declared["CORE"] & self.declared["RIM"])
        self.assertFalse(self.declared["ENGINE"] & self.declared["RIM"])
        for layer, names in self.declared.items():
            for name in sorted(names):
                self.assertTrue(hasattr(ctx, name), f"{layer}_API names {name}, which ctx lacks")
        for tup in (ctx.CORE_API, ctx.ENGINE_API, ctx.RIM_API):
            self.assertEqual(len(tup), len(set(tup)), "duplicate in an API tuple")

    def test_each_name_is_defined_in_the_region_its_tuple_claims(self):
        for layer, names in self.declared.items():
            for name in sorted(names):
                self.assertIn(name, self.top, f"{name} is not a top-level definition")
                lineno = self.top[name][0]
                self.assertEqual(layer_of(self.regions, lineno), layer,
                                 f"{name} (line {lineno}) is listed in {layer}_API but defined "
                                 f"under the {layer_of(self.regions, lineno)} banner")

    def test_rim_names_are_reached_only_by_research_ui(self):
        for rel, used in self.scanned.items():
            rim = used & self.declared["RIM"]
            if rel == "tools/research_ui.py":
                self.assertEqual(rim, self.declared["RIM"], "research_ui no longer hosts the SEC projections")
            else:
                self.assertEqual(rim, set(), f"{rel} reaches RIM names {sorted(rim)}")

    def test_the_scan_is_not_vacuous(self):
        self.assertGreaterEqual(len(self.union), 25)
        self.assertGreaterEqual(len(self.scanned["tools/note.py"]), 15)


# ── banners and layering ─────────────────────────────────────────────────────
class BannersAndLayeringTests(_Source, unittest.TestCase):
    def test_eight_layer_banners_in_the_ratified_order(self):
        layers = [lay for _, lay in self.regions if lay in LAYERS]
        self.assertEqual(layers, EXPECTED_ORDER)
        self.assertEqual(self.regions[-1][1], "CLI", "main() must sit under the CLI marker, not a layer")
        # the first banner precedes the path globals; nothing executable is unlabelled
        first = self.regions[0][0]
        self.assertLess(first, self.top["REPO"][0])
        self.assertEqual(layer_of(self.regions, self.top["REPO"][0]), "CORE")

    def test_engine_never_references_rim_except_through_the_seams(self):
        rim = self.by_layer.get("RIM", set())
        self.assertTrue(rim, "no RIM-region definitions found — banners missing?")
        for name in sorted(self.by_layer.get("ENGINE", set())):
            bad = (_loads(self.top[name][1]) & rim) - set(ctx.SEAMS)
            self.assertEqual(bad, set(), f"ENGINE `{name}` references RIM name(s) {sorted(bad)}")

    def test_seams_are_exactly_the_declared_three(self):
        self.assertEqual(ctx.SEAMS, ("REDACT", "BANNER", "_RUNTIME_ARTIFACTS"))
        for s in ctx.SEAMS:
            self.assertTrue(hasattr(ctx, s))
        # each seam is actually crossed by ENGINE — a seam nobody uses is a stale declaration
        rim = self.by_layer.get("RIM", set())
        crossed = set()
        for name in self.by_layer.get("ENGINE", set()):
            crossed |= _loads(self.top[name][1]) & (rim | set(ctx.SEAMS))
        self.assertEqual(crossed & set(ctx.SEAMS), set(ctx.SEAMS))

    def test_the_four_sec_projections_and_serve_are_rim(self):
        for name in ctx.RIM_API + ("cmd_serve", "_web_banner", "perf_summary", "cmd_perf",
                                   "operator_fact_drift", "cmd_brief"):
            self.assertEqual(layer_of(self.regions, self.top[name][0]), "RIM", name)

    def test_the_engine_commands_are_engine(self):
        for name in ("build_graph", "_parse_web_text", "_render_graph_html", "_serve_route",
                     "cmd_graph", "cmd_health", "cmd_frontier", "cmd_init", "cmd_related",
                     "doc_topology", "SCHEMA", "ID_RX", "SUPERSEDED_TAG_RX", "_NODE_REF_RX"):
            self.assertEqual(layer_of(self.regions, self.top[name][0]), "ENGINE", name)


